create or replace function public.save_round_results(
  p_round_id bigint,
  p_results jsonb
)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  expected_count integer;
  updated_count integer;
  target_round_number integer;
begin
  if not public.is_admin() then
    raise exception 'Admin access required.';
  end if;

  select round_number into target_round_number
  from public.rounds where id = p_round_id for update;
  if target_round_number is null then
    raise exception 'The selected round does not exist.';
  end if;

  if exists (
    select 1
    from public.round_processing_runs as processing
    join public.rounds as processed_round on processed_round.id = processing.round_id
    where processed_round.round_number > target_round_number
  ) then
    raise exception 'Results cannot be changed because a later round has already been processed.';
  end if;

  if jsonb_typeof(p_results) <> 'array' then
    raise exception 'Round results must be provided as a list.';
  end if;

  select count(*) into expected_count
  from public.fixtures where round_id = p_round_id;

  if expected_count = 0 then
    raise exception 'This round has no fixtures.';
  end if;

  if jsonb_array_length(p_results) <> expected_count then
    raise exception 'Provide a score for every fixture in this round.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_results)
      as supplied(fixture_id bigint, home_score integer, away_score integer)
    where supplied.fixture_id is null
      or supplied.home_score is null
      or supplied.away_score is null
      or supplied.home_score < 0
      or supplied.away_score < 0
  ) then
    raise exception 'Scores must be non-negative whole numbers for every fixture.';
  end if;

  update public.fixtures as fixture
  set home_score = supplied.home_score,
      away_score = supplied.away_score,
      result = case
        when supplied.home_score > supplied.away_score then 'home_win'
        when supplied.home_score < supplied.away_score then 'away_win'
        else 'draw'
      end
  from jsonb_to_recordset(p_results)
    as supplied(fixture_id bigint, home_score integer, away_score integer)
  where fixture.id = supplied.fixture_id
    and fixture.round_id = p_round_id;

  get diagnostics updated_count = row_count;
  if updated_count <> expected_count then
    raise exception 'The submitted fixture list does not match this round.';
  end if;

  return updated_count;
end;
$$;

create or replace function public.process_round(
  p_round_id bigint,
  p_confirm_reprocess boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  round_record record;
  participant_record record;
  selection_record record;
  run_id bigint;
  run_number integer;
  fixture_count integer;
  v_active_count integer;
  v_eliminated_count integer := 0;
  outcome_value text;
  result_value text;
  status_before_value text;
  status_after_value text;
  expected_result text;
begin
  if not public.is_admin() then
    raise exception 'Admin access required.';
  end if;

  select id, round_number, status, draw_rule
  into round_record
  from public.rounds
  where id = p_round_id
  for update;

  if not found then
    raise exception 'The selected round does not exist.';
  end if;

  if exists (
    select 1 from public.round_processing_runs
    where round_id = p_round_id
  ) and not p_confirm_reprocess then
    raise exception 'This round has already been processed. Confirm reprocessing to continue.';
  end if;

  if exists (
    select 1
    from public.round_processing_runs as processing
    join public.rounds as processed_round on processed_round.id = processing.round_id
    where processed_round.round_number > round_record.round_number
  ) then
    raise exception 'This round cannot be reprocessed after a later round has been processed.';
  end if;

  select count(*) into fixture_count
  from public.fixtures where round_id = p_round_id;

  if fixture_count = 0 then
    raise exception 'This round has no fixtures.';
  end if;

  if exists (
    select 1
    from public.fixtures
    where round_id = p_round_id
      and (
        (home_score is null or away_score is null)
        and result not in ('home_win', 'away_win', 'draw')
      )
  ) then
    raise exception 'Every fixture needs a saved score or recorded result before processing.';
  end if;

  if exists (
    select 1
    from public.profiles as participant
     where (participant.competition_status = 'active'
       or participant.eliminated_round_id = p_round_id)
      and not exists (
      select 1
      from public.selections as selection
      join public.fixtures as fixture
        on fixture.id = selection.fixture_id
       and fixture.round_id = selection.round_id
       and selection.team_id in (fixture.home_team_id, fixture.away_team_id)
      where selection.user_id = participant.id
        and selection.round_id = p_round_id
    )
  ) then
    raise exception 'Every active participant must have a valid selection for this round.';
  end if;

  select coalesce(max(processing.run_number), 0) + 1
  into run_number
  from public.round_processing_runs as processing
  where processing.round_id = p_round_id;

  insert into public.round_processing_runs(round_id, run_number, processed_by)
  values (p_round_id, run_number, auth.uid())
  returning id into run_id;

  for participant_record in
    select participant.id,
      coalesce(nullif(participant.display_name, ''), participant.username, participant.id::text) as participant_name,
      participant.competition_status,
      participant.eliminated_round_id
    from public.profiles as participant
    where participant.competition_status = 'active'
       or participant.eliminated_round_id = p_round_id
    order by participant_name
  loop
    select selection.id as selection_id,
      selection.team_id,
      team.name as team_name,
      fixture.id as fixture_id,
      fixture.home_team_id,
      fixture.away_team_id,
      home_team.name || ' vs ' || away_team.name as fixture_label,
      fixture.home_score,
      fixture.away_score,
      fixture.result
    into selection_record
    from public.selections as selection
    join public.fixtures as fixture
      on fixture.id = selection.fixture_id
     and fixture.round_id = selection.round_id
     and selection.team_id in (fixture.home_team_id, fixture.away_team_id)
    join public.teams as team on team.id = selection.team_id
    join public.teams as home_team on home_team.id = fixture.home_team_id
    join public.teams as away_team on away_team.id = fixture.away_team_id
    where selection.user_id = participant_record.id
      and selection.round_id = p_round_id;

    if selection_record.home_score is not null then
      result_value := case
        when selection_record.home_score > selection_record.away_score then 'home_win'
        when selection_record.home_score < selection_record.away_score then 'away_win'
        else 'draw'
      end;
    else
      result_value := selection_record.result;
    end if;

    expected_result := case
      when result_value = 'draw' then round_record.draw_rule
      when result_value = 'home_win'
        and selection_record.team_id = selection_record.home_team_id then 'survive'
      when result_value = 'away_win'
        and selection_record.team_id = selection_record.away_team_id then 'survive'
      else 'eliminate'
    end;

    outcome_value := case when expected_result = 'survive' then 'survived' else 'eliminated' end;
    status_before_value := participant_record.competition_status;
    status_after_value := case when outcome_value = 'survived' then 'active' else 'eliminated' end;

    update public.profiles
    set competition_status = status_after_value,
        eliminated_round_id = case
          when status_after_value = 'eliminated' then p_round_id
          else null
        end,
        updated_at = clock_timestamp()
    where id = participant_record.id;

    if status_before_value <> 'eliminated'
      and status_after_value = 'eliminated' then
      v_eliminated_count := v_eliminated_count + 1;
    end if;

    insert into public.round_processing_entries (
      run_id, profile_id, participant_name, selection_id,
      selected_team_id, selected_team_name, fixture_id,
      fixture_label, fixture_result, home_score, away_score,
      outcome, status_before, status_after
    ) values (
      run_id, participant_record.id, participant_record.participant_name,
      selection_record.selection_id, selection_record.team_id,
      selection_record.team_name, selection_record.fixture_id,
      selection_record.fixture_label, result_value,
      selection_record.home_score, selection_record.away_score,
      outcome_value, status_before_value, status_after_value
    );
  end loop;

  select count(*) into v_active_count
  from public.profiles where competition_status = 'active';

  update public.rounds
  set status = 'complete', processed_at = clock_timestamp()
  where id = p_round_id;

  update public.round_processing_runs
    set active_count = v_active_count,
      eliminated_count = v_eliminated_count
  where id = run_id;

  return jsonb_build_object(
    'run_id', run_id,
    'run_number', run_number,
    'round_number', round_record.round_number,
    'active_count', v_active_count,
    'eliminated_count', v_eliminated_count
  );
end;
$$;

revoke all on function public.save_round_results(bigint, jsonb) from public, anon;
revoke all on function public.process_round(bigint, boolean) from public, anon;
grant execute on function public.save_round_results(bigint, jsonb) to authenticated;
grant execute on function public.process_round(bigint, boolean) to authenticated;

