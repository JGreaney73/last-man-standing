create or replace function public.allocate_overdue_round_selections()
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  round_record record;
  player_record record;
  team_id_to_assign bigint;
  fixture_id_for_team bigint;
  assigned_count integer := 0;
  first_kickoff timestamptz;
begin
  for round_record in
    select id, status, first_kickoff
    from public.rounds
    where status in ('open', 'scheduled')
    order by id
    for update skip locked
  loop
    select coalesce(min(kickoff), round_record.first_kickoff)
    into first_kickoff
    from public.fixtures
    where round_id = round_record.id;

    if first_kickoff is null
      or clock_timestamp() < first_kickoff - interval '2 hours' then
      continue;
    end if;

    for player_record in
      select id
      from public.profiles
      where competition_status = 'active'
        and not exists (
          select 1 from public.selections
          where user_id = profiles.id and round_id = round_record.id
        )
      order by id
    loop
      select teams.id, fixture.id
      into team_id_to_assign, fixture_id_for_team
      from public.teams
      join public.fixtures as fixture
        on fixture.round_id = round_record.id
       and teams.id in (fixture.home_team_id, fixture.away_team_id)
      where teams.is_active
        and not exists (
          select 1 from public.selections
          where user_id = player_record.id and team_id = teams.id
        )
      order by teams.name, teams.id, fixture.kickoff
      limit 1;

      if team_id_to_assign is null then
        continue;
      end if;

      insert into public.selections (
        user_id, round_id, fixture_id, team_id, is_automatic, selection_source
      ) values (
        player_record.id, round_record.id, fixture_id_for_team,
        team_id_to_assign, true, 'AUTO'
      )
      on conflict (user_id, round_id) do nothing;

      if found then
        assigned_count := assigned_count + 1;
      end if;

      team_id_to_assign := null;
      fixture_id_for_team := null;
    end loop;

    update public.rounds
    set status = 'locked'
    where id = round_record.id
      and status in ('open', 'scheduled');
  end loop;

  return assigned_count;
end;
$$;
