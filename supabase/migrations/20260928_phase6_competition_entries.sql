alter table public.selections
  drop constraint if exists selections_user_id_round_id_key;

create unique index if not exists selections_entry_id_round_id_key
  on public.selections(entry_id, round_id);

create index if not exists selections_entry_id_idx
  on public.selections(entry_id);

alter table public.round_processing_entries
  add column if not exists entry_id bigint references public.competition_entries(id) on delete set null;

update public.round_processing_entries as audit
set entry_id = selection.entry_id
from public.selections as selection
where audit.selection_id = selection.id
  and audit.entry_id is null;

