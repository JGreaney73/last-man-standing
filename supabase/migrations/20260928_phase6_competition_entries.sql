  on public.teams for select to authenticated using (true);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  new_profile_id uuid;
begin
  insert into public.profiles (id, username, display_name)
  values (
    new.id,
    nullif(new.raw_user_meta_data ->> 'username', ''),
    coalesce(new.raw_user_meta_data ->> 'display_name', new.email)
  )
  returning id into new_profile_id;

  insert into public.competition_entries(user_id, entry_number, name)
  values (new_profile_id, 1, coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), new.email) || ' - Entry 1');

  return new;
end;
$$;

create or replace function public.create_competition_entry()
returns public.competition_entries
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  next_entry_number integer;
  created_entry public.competition_entries;
  first_round_lockout timestamptz;
begin
  if auth.uid() is null then
    raise exception 'Sign-in is required to create an entry.';
  end if;

  perform pg_advisory_xact_lock(20260928, 1);

  perform 1 from public.profiles where id = auth.uid() for update;
  if not found then
    raise exception 'Player profile was not found.';
  end if;

  if exists (select 1 from public.round_processing_runs) then
    raise exception 'New entries are closed because competition processing has started.';
  end if;

  select coalesce(min(fixture.kickoff), min(round.first_kickoff)) - interval '2 hours'
  into first_round_lockout
  from public.rounds as round
  left join public.fixtures as fixture on fixture.round_id = round.id
  where round.status in ('open', 'scheduled');

  if first_round_lockout is not null and clock_timestamp() >= first_round_lockout then
    raise exception 'New entries are closed because the first-round selection deadline has passed.';
  end if;

  select coalesce(max(entry_number), 0) + 1
  into next_entry_number
  from public.competition_entries
  where user_id = auth.uid();

  insert into public.competition_entries(user_id, entry_number, name)
  values (
    auth.uid(),
    next_entry_number,
    coalesce((select nullif(display_name, '') from public.profiles where id = auth.uid()), 'Entry')
      || ' - Entry ' || next_entry_number
  )
  returning * into created_entry;

  return created_entry;
end;
$$;

revoke all on function public.create_competition_entry() from public, anon;
grant execute on function public.create_competition_entry() to authenticated;

create or replace function public.enforce_selection_deadline()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  round_status text;
  configured_kickoff timestamptz;
  first_kickoff timestamptz;
  entry_owner uuid;
  entry_status text;
begin
  if tg_op = 'DELETE' then
    return old;
  end if;

  if auth.uid() is not null then
    if new.user_id <> auth.uid() then
      raise exception 'You can only change your own selection.';
    end if;
    if tg_op = 'UPDATE'
      and (new.user_id <> old.user_id or new.round_id <> old.round_id or new.entry_id <> old.entry_id) then
      raise exception 'A saved selection cannot be moved to another user, round, or entry.';
    end if;
    new.is_automatic := false;
    new.selection_source := 'MANUAL';
  elsif new.selection_source = 'AUTO' and new.is_automatic then
    return new;
  end if;

  select user_id, competition_status
  into entry_owner, entry_status
  from public.competition_entries
  where id = new.entry_id
  for update;

  if not found or entry_owner <> new.user_id then
    raise exception 'The selected entry does not belong to this account.';
  end if;
  if entry_status <> 'active' then
    raise exception 'This entry has been eliminated and cannot make or change selections.';
  end if;

  select status, rounds.first_kickoff
  into round_status, configured_kickoff
  from public.rounds
  where id = new.round_id
  for update;
  if not found then
    raise exception 'The selected round does not exist.';
  end if;

  select coalesce(min(kickoff), configured_kickoff)
  into first_kickoff
  from public.fixtures
  where round_id = new.round_id;

  if first_kickoff is null then
    raise exception 'This round has no kickoff time, so selections are unavailable.';
  end if;
  if round_status not in ('open', 'scheduled')
    or clock_timestamp() >= first_kickoff - interval '2 hours' then
    raise exception 'Selections are now locked for this round.';
  end if;

  if new.fixture_id is not null and not exists (
    select 1 from public.fixtures
    where id = new.fixture_id
      and round_id = new.round_id
      and new.team_id in (home_team_id, away_team_id)
  ) then
    raise exception 'The selected team is not in that round fixture.';
  end if;

  if exists (
    select 1 from public.selections
    where entry_id = new.entry_id
      and team_id = new.team_id
      and round_id <> new.round_id
  ) then
    raise exception 'This entry has already selected this team in another round.';
  end if;

  return new;
end;
$$;

