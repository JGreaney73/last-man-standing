create table if not exists public.competition_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  entry_number integer not null check (entry_number > 0),
  name text not null,
  competition_status text not null default 'active'
    check (competition_status in ('active', 'eliminated')),
  eliminated_round_id bigint references public.rounds(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  unique (user_id, entry_number)
);

insert into public.competition_entries (
  user_id, entry_number, name, competition_status, eliminated_round_id
)
select profile.id,
  1,
  coalesce(nullif(profile.display_name, ''), profile.username, 'Entry') || ' - Entry 1',
  profile.competition_status,
  profile.eliminated_round_id
from public.profiles as profile
where not exists (
  select 1 from public.competition_entries as entry where entry.user_id = profile.id
);

